CREATE TABLE Hotels (
  HotelId VARCHAR2(36 CHAR) NOT NULL,
  Name VARCHAR2(200 CHAR) NOT NULL,
  CreatedAt TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (HotelId)
);

CREATE UNIQUE INDEX HotelsByName ON Hotels(Name);

CREATE TABLE Rooms (
  RoomId VARCHAR2(36 CHAR) NOT NULL,
  HotelId VARCHAR2(36 CHAR) NOT NULL,
  RoomNumber VARCHAR2(10 CHAR) NOT NULL,
  RoomType VARCHAR2(16 CHAR) NOT NULL,
  Capacity NUMBER(19,0) NOT NULL,
  PRIMARY KEY (RoomId)
);

CREATE UNIQUE INDEX RoomsByHotelAndNumber ON Rooms(HotelId, RoomNumber);

CREATE TABLE Bookings (
  BookingId VARCHAR2(36 CHAR) NOT NULL,
  Reference VARCHAR2(35 CHAR) NOT NULL,
  HotelId VARCHAR2(36 CHAR) NOT NULL,
  RoomId VARCHAR2(36 CHAR) NOT NULL,
  GuestName VARCHAR2(200 CHAR) NOT NULL,
  GuestCount NUMBER(19,0) NOT NULL,
  CheckInDate DATE NOT NULL,
  CheckOutDate DATE NOT NULL,
  CreatedAt TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (BookingId)
);

CREATE UNIQUE INDEX BookingsByReference ON Bookings(Reference);

CREATE TABLE OccupiedNights (
  RoomId VARCHAR2(36 CHAR) NOT NULL,
  StayDate DATE NOT NULL,
  BookingId VARCHAR2(36 CHAR) NOT NULL,
  PRIMARY KEY (RoomId, StayDate)
);

CREATE TABLE OutboxEvents (
  EventId VARCHAR2(36 CHAR) NOT NULL,
  BookingId VARCHAR2(36 CHAR) NOT NULL,
  Payload CLOB NOT NULL,
  CreatedAt TIMESTAMP(6) NOT NULL,
  PublishedAt TIMESTAMP(6),
  PRIMARY KEY (EventId)
);

CREATE TABLE ProcessedEvents (
  EventId VARCHAR2(36 CHAR) NOT NULL,
  BookingId VARCHAR2(36 CHAR) NOT NULL,
  ProcessedAt TIMESTAMP(6) NOT NULL,
  PRIMARY KEY (EventId)
);
